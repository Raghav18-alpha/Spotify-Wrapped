USE music_wrapped;

-- 1. DATABASE AND TABLES: demonstrate the database objects.
SHOW DATABASES;
SHOW TABLES;

-- 2. TABLE STRUCTURE: columns, data types, keys and constraints.
DESCRIBE users;
DESCRIBE songs;
DESCRIBE listening_history;

-- 3. READ DATA: show the sample users stored in the database.
SELECT user_id, name, email, country, plan_type
FROM users
ORDER BY user_id;

-- 4. AGGREGATE FUNCTION: count users by subscription plan.
SELECT plan_type, COUNT(*) AS total_users
FROM users
GROUP BY plan_type
ORDER BY plan_type;

-- 5. JOIN: show listening records with the user and song names.
SELECT u.name AS listener, s.title AS song, h.played_at, h.ms_played
FROM listening_history AS h
JOIN users AS u ON u.user_id = h.user_id
JOIN songs AS s ON s.song_id = h.song_id
ORDER BY h.played_at
LIMIT 15;

-- 6. GROUP BY + aggregate functions: total plays and minutes per user in 2026.
SELECT u.name,
       COUNT(h.listen_id) AS total_plays,
       ROUND(COALESCE(SUM(h.ms_played), 0) / 60000, 2) AS total_minutes
FROM users AS u
LEFT JOIN listening_history AS h
  ON h.user_id = u.user_id
 AND h.played_at >= '2026-01-01'
 AND h.played_at <  '2027-01-01'
GROUP BY u.user_id, u.name
ORDER BY total_minutes DESC;

-- 7. JOIN across music tables: most-played songs in 2026.
SELECT s.title, COUNT(*) AS plays
FROM listening_history AS h
JOIN songs AS s ON s.song_id = h.song_id
WHERE h.played_at >= '2026-01-01'
  AND h.played_at <  '2027-01-01'
GROUP BY s.song_id, s.title
ORDER BY plays DESC, s.title
LIMIT 5;

-- 8. VIEW: global artist ranking.
SELECT * FROM v_top_artists_global
ORDER BY qualified_plays DESC, artist_name
LIMIT 10;

-- 9. STORED FUNCTION: classify a sample user's listening style.
SELECT name, get_listener_type(user_id, 2026) AS listener_type
FROM users
ORDER BY user_id;

-- 10. STORED PROCEDURE: generate Wrapped summaries for all sample users for 2026.
-- This updates/inserts summary rows in wrapped_summary. Run it when ready to demo routines.
CALL generate_wrapped_all(2026);

-- 11. VIEW: show the summaries generated by the procedure above.
SELECT name, wrapped_year, top_song, top_artist,
       total_minutes, longest_streak, listener_type
FROM v_user_wrapped
WHERE wrapped_year = 2026
ORDER BY name;

