st.title("🎧 MUSIC WRAPPED")
st.caption("A database-powered year in listening · Python + Streamlit frontend · MySQL relational database")

try:
    users = fetch_all("SELECT user_id, name, country, email, plan_type FROM users ORDER BY name")
except Exception as exc:
    st.error("Cannot connect to MySQL. Start the MySQL server and check your .env settings.")
    st.code(str(exc))
    st.stop()
if not users:
    st.warning("No users are in the database yet. Import database/schema.sql and database/seed.sql first.")
    st.stop()

wrapped_tab, lab_tab, schema_tab, about_tab = st.tabs(["✨ Your Wrapped", "🧪 DBMS Query Lab", "🗂️ Schema Explorer", "🎓 Viva Guide"])

with wrapped_tab:
    st.subheader("Generate a listener's year in sound")
    labels = {f"{u['name']} · {u['country']} · {u['plan_type']}": u['user_id'] for u in users}
    c1, c2 = st.columns([3, 1])
    with c1:
        chosen = st.selectbox("Choose a sample listener", list(labels), key="wrapped_user")
    with c2:
        year = st.selectbox("Listening year", [2026, 2025, 2024, 2023], key="wrapped_year")
    if st.button("✨ Generate my Wrapped", use_container_width=True, type="primary"):
        uid = labels[chosen]
        conn = get_connection()
        try:
            cur = conn.cursor()
            cur.callproc("generate_wrapped", [uid, int(year)])
            conn.commit()
            st.success("Wrapped summary generated by the MySQL stored procedure `generate_wrapped`.")
        except Exception as exc:
            conn.rollback()
            st.error("Stored procedure failed. Check that database/routines.sql has been imported.")
            st.code(str(exc))
            st.stop()
        finally:
            conn.close()
        st.session_state["last_wrapped"] = (uid, int(year))
    current = st.session_state.get("last_wrapped")
    if current:
        uid, selected_year = current
        summary = fetch_all("""SELECT u.name,u.country,u.plan_type,w.total_minutes,w.longest_streak,w.listener_type,
            so.title top_song,a.name top_artist FROM users u
            LEFT JOIN wrapped_summary w ON w.user_id=u.user_id AND w.wrapped_year=%s
            LEFT JOIN songs so ON so.song_id=w.top_song_id
            LEFT JOIN artists a ON a.artist_id=w.top_artist_id WHERE u.user_id=%s""", (selected_year, uid))[0]
        totals = fetch_all("SELECT COUNT(*) plays,COALESCE(SUM(ms_played)/60000,0) minutes FROM listening_history WHERE user_id=%s AND YEAR(played_at)=%s", (uid, selected_year))[0]
        genre = fetch_all("""SELECT g.name,COUNT(*) plays FROM listening_history h JOIN songs s USING(song_id)
            JOIN genres g USING(genre_id) WHERE h.user_id=%s AND YEAR(h.played_at)=%s
            GROUP BY g.genre_id,g.name ORDER BY plays DESC LIMIT 1""", (uid, selected_year))
        songs = fetch_all("""SELECT s.title song, GROUP_CONCAT(DISTINCT a.name ORDER BY a.name SEPARATOR ', ') artist, COUNT(*) plays
            FROM listening_history h JOIN songs s USING(song_id) JOIN song_artist sa USING(song_id)
            JOIN artists a USING(artist_id) WHERE h.user_id=%s AND YEAR(h.played_at)=%s
            GROUP BY s.song_id,s.title ORDER BY plays DESC LIMIT 5""", (uid, selected_year))
        artists = fetch_all("""SELECT a.name artist,COUNT(*) plays FROM listening_history h
            JOIN song_artist sa USING(song_id) JOIN artists a USING(artist_id)
            WHERE h.user_id=%s AND YEAR(h.played_at)=%s GROUP BY a.artist_id,a.name
            ORDER BY plays DESC LIMIT 5""", (uid, selected_year))
        night = fetch_all("SELECT COUNT(*) n FROM listening_history WHERE user_id=%s AND YEAR(played_at)=%s AND HOUR(played_at) BETWEEN 0 AND 3", (uid, selected_year))[0]['n']
        night_pct = night / totals['plays'] * 100 if totals['plays'] else 0
        st.divider()
        st.header(f"{summary['name']}'s {selected_year} in sound")
        st.caption(f"{summary['country']} · {summary['plan_type']} plan · fictional sample data")
        m1,m2,m3,m4 = st.columns(4)
        m1.metric("Minutes listened", f"{float(summary['total_minutes'] or 0):,.1f}")
        m2.metric("Total plays", f"{totals['plays']:,}")
        m3.metric("Longest streak", f"{summary['longest_streak'] or 0} days")
        m4.metric("Listener type", summary['listener_type'] or "Quiet Year")
        left,right = st.columns(2)
        with left:
            st.markdown("### 🏆 Top song")
            st.subheader(summary['top_song'] or "No plays recorded")
            st.markdown("### 🎤 Top artist")
            st.subheader(summary['top_artist'] or "No plays recorded")
        with right:
            st.markdown("### 🎨 Favorite genre")
            st.subheader(genre[0]['name'] if genre else "No genre data")
            st.markdown("### 🦉 Night-owl score")
            st.subheader(f"{night_pct:.1f}%")
            st.caption("Percentage of plays between midnight and 4 AM")
        left,right = st.columns(2)
        with left:
            st.markdown("### 🔥 Top songs")
            st.dataframe(pd.DataFrame(songs) if songs else pd.DataFrame(), hide_index=True, use_container_width=True)
        with right:
            st.markdown("### 🌟 Top artists")
            if artists:
                st.bar_chart(pd.DataFrame(artists).set_index("artist"))
            else:
                st.info("No artist data for this year.")
    else:
        st.info("Choose a listener and year, then generate a Wrapped summary. The summary is calculated by MySQL and displayed here.")
        st.markdown("**DBMS concepts behind this screen:** SELECT, JOIN, GROUP BY, aggregate functions, stored procedure, and a summary table.")

with lab_tab:
    st.subheader("Live DBMS Query Lab")
    st.write("Choose a prepared query, inspect the SQL, then run it against your actual `music_wrapped` database. Results appear below.")
    demos = {
        "1 · Show all tables": ("SHOW TABLES", "Lists tables and views in the selected database."),
        "2 · View user records": ("SELECT user_id, name, email, country, plan_type FROM users ORDER BY user_id", "SELECT retrieves records from a table. These are fictional demo users."),
        "3 · Table structure / schema": ("DESCRIBE users", "Shows columns, data types, null rules, keys, and defaults."),
        "4 · Aggregate: users by plan": ("SELECT plan_type, COUNT(*) AS total_users FROM users GROUP BY plan_type ORDER BY total_users DESC", "COUNT and GROUP BY summarize records by subscription plan."),
        "5 · JOIN: songs with artist and genre": ("SELECT s.title AS song, GROUP_CONCAT(DISTINCT a.name ORDER BY a.name SEPARATOR ', ') AS artists, g.name AS genre FROM songs s JOIN genres g ON g.genre_id=s.genre_id JOIN song_artist sa ON sa.song_id=s.song_id JOIN artists a ON a.artist_id=sa.artist_id GROUP BY s.song_id,s.title,g.name ORDER BY s.title LIMIT 20", "JOIN connects related tables using keys; GROUP_CONCAT combines artist names."),
        "6 · Top songs by play count": ("SELECT s.title, COUNT(h.listen_id) AS plays FROM songs s LEFT JOIN listening_history h ON h.song_id=s.song_id GROUP BY s.song_id,s.title ORDER BY plays DESC, s.title LIMIT 10", "LEFT JOIN keeps songs even when they have no listening records; COUNT aggregates plays."),
        "7 · Global artist view": ("SELECT * FROM v_top_artists_global ORDER BY qualified_plays DESC LIMIT 10", "Reads from a SQL VIEW, a stored query presented like a virtual table."),
        "8 · Wrapped summaries view": ("SELECT name, country, wrapped_year, top_song, top_artist, total_minutes, longest_streak, listener_type FROM v_user_wrapped ORDER BY wrapped_year DESC, name LIMIT 20", "Demonstrates a view joining user, summary, song, and artist data."),
        "9 · Indexes on listening history": ("SHOW INDEX FROM listening_history", "Shows indexes that can help queries filter listening records efficiently."),
        "10 · Listening minutes by user": ("SELECT u.name, ROUND(SUM(h.ms_played)/60000, 2) AS minutes_listened FROM users u JOIN listening_history h ON h.user_id=u.user_id GROUP BY u.user_id,u.name ORDER BY minutes_listened DESC", "SUM and GROUP BY calculate a per-user statistic from related tables."),
    }
    choice = st.selectbox("Choose a DBMS demonstration", list(demos.keys()))
    sql, explanation = demos[choice]
    st.markdown("**SQL query (visible for your teacher):**")
    st.code(sql, language="sql")
    st.caption("Concept: " + explanation)
    if st.button("▶ Run this SQL query", type="primary"):
        try:
            rows = fetch_all(sql)
            st.success(f"Query executed successfully · {len(rows)} row(s) returned")
            if rows:
                st.dataframe(pd.DataFrame(rows), use_container_width=True, hide_index=True)
            else:
                st.info("The query ran successfully but returned no rows.")
        except Exception as exc:
            st.error("This query could not run. Check that schema.sql, seed.sql, and routines.sql were imported.")
            st.code(str(exc))
    st.info("For your teacher: select a query, show the SQL statement, click Run, and explain the result. The lab only runs the prepared read-only demonstration queries.")

with schema_tab:
    st.subheader("Database Schema Explorer")
    st.write("Explore the real tables, columns, and relationships stored in MySQL.")
    try:
        table_rows = fetch_all("SELECT TABLE_NAME, TABLE_TYPE FROM information_schema.TABLES WHERE TABLE_SCHEMA=%s ORDER BY TABLE_TYPE,TABLE_NAME", ("music_wrapped",))
        st.markdown("### Tables and views")
        st.dataframe(pd.DataFrame(table_rows), hide_index=True, use_container_width=True)
        table_names = [r['TABLE_NAME'] for r in table_rows]
        selected_table = st.selectbox("Inspect a table or view", table_names)
        cols = fetch_all("SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY, COLUMN_DEFAULT, EXTRA FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=%s AND TABLE_NAME=%s ORDER BY ORDINAL_POSITION", ("music_wrapped", selected_table))
        st.markdown(f"### Structure: `{selected_table}`")
        st.dataframe(pd.DataFrame(cols), hide_index=True, use_container_width=True)
        if st.button("Preview up to 20 rows"):
            # Table name is selected from information_schema, not free-form user input.
            preview = fetch_all(f"SELECT * FROM `{selected_table}` LIMIT 20")
            st.dataframe(pd.DataFrame(preview), hide_index=True, use_container_width=True)
    except Exception as exc:
        st.error("Could not inspect schema.")
        st.code(str(exc))

